/**
 * Generates the static PWA assets that can't come from React:
 *   public/icons/icon-192.png, icon-512.png   — "any" icons (rounded, like src/app/icon.svg)
 *   public/icons/icon-maskable-512.png        — full-bleed, glyph inside the 80% safe zone
 *   src/app/apple-icon.png (180×180)          — iOS home screen (full-bleed; iOS rounds it)
 *   public/offline.html                       — bilingual page the service worker shows offline
 *
 * Run after changing the logo or the `offline` dictionary strings:
 *   npm run pwa:assets
 * The outputs are committed, so builds and deployments don't need this script.
 * `sharp` is used through Next.js's own dependency (next → sharp).
 */
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";

import sharp from "sharp";

import { ar } from "../src/i18n/dictionaries/ar";
import { en, type Dictionary } from "../src/i18n/dictionaries/en";

const root = path.resolve(import.meta.dirname, "..");
const ACCENT = "#256abf";

/** The robot glyph from src/app/icon.svg, in a 32×32 box. */
const GLYPH = `<g fill="none" stroke="#fff" stroke-width="2.2" stroke-linecap="round" stroke-linejoin="round"><rect x="8" y="11" width="16" height="12" rx="3"/><path d="M16 7v4M12.5 16v1.5M19.5 16v1.5"/></g>`;
const roundedSvg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32"><rect width="32" height="32" rx="8" fill="${ACCENT}"/>${GLYPH}</svg>`;
const fullBleedSvg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32"><rect width="32" height="32" fill="${ACCENT}"/>${GLYPH}</svg>`;

async function png(svg: string, size: number, file: string, { opaque = false } = {}) {
  let image = sharp(Buffer.from(svg), { density: (72 * size) / 32 }).resize(size, size);
  // iOS paints transparent pixels black, so full-bleed icons are flattened to RGB.
  if (opaque) image = image.flatten({ background: ACCENT });
  await image.png({ compressionLevel: 9 }).toFile(path.join(root, file));
  console.log(`wrote ${file}`);
}

const escapeHtml = (value: string) =>
  value.replaceAll("&", "&amp;").replaceAll("<", "&lt;").replaceAll(">", "&gt;").replaceAll('"', "&quot;");

function offlineHtml() {
  const block = (lang: "en" | "ar", dict: Dictionary) => `
      <section lang="${lang}" dir="${lang === "ar" ? "rtl" : "ltr"}">
        <h1>${escapeHtml(dict.offline.title)}</h1>
        <p>${escapeHtml(dict.offline.body)}</p>
        <button type="button" onclick="location.reload()">${escapeHtml(dict.offline.retry)}</button>
      </section>`;

  return `<!doctype html>
<!-- Generated by scripts/generate-pwa-assets.ts from the i18n dictionaries. Do not edit by hand. -->
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover" />
    <meta name="robots" content="noindex" />
    <meta name="theme-color" content="#fcfcfb" media="(prefers-color-scheme: light)" />
    <meta name="theme-color" content="#1a1a19" media="(prefers-color-scheme: dark)" />
    <title>${escapeHtml(en.offline.title)} · ${escapeHtml(en.meta.appName)}</title>
    <style>
      :root { color-scheme: light dark; --page: #f5f5f2; --surface: #fcfcfb; --line: #e1e0d9; --ink: #0b0b0b; --ink-2: #52514e; --accent: #256abf; }
      @media (prefers-color-scheme: dark) { :root { --page: #0d0d0d; --surface: #1a1a19; --line: #2c2c2a; --ink: #f0efec; --ink-2: #c3c2b7; } }
      * { box-sizing: border-box; }
      body { margin: 0; min-height: 100dvh; display: grid; place-items: center; background: var(--page); color: var(--ink);
        font-family: system-ui, -apple-system, "Segoe UI", "Noto Sans Arabic", "Geeza Pro", sans-serif;
        padding: max(1.5rem, env(safe-area-inset-top)) max(1rem, env(safe-area-inset-right)) max(1.5rem, env(safe-area-inset-bottom)) max(1rem, env(safe-area-inset-left)); }
      main { width: 100%; max-width: 26rem; background: var(--surface); border: 1px solid var(--line); border-radius: 1rem; padding: 1.5rem; }
      .logo { width: 48px; height: 48px; display: block; margin-bottom: 1rem; }
      section + section { border-top: 1px solid var(--line); margin-top: 1.25rem; padding-top: 1.25rem; }
      h1 { font-size: 1.125rem; margin: 0 0 0.5rem; }
      p { margin: 0 0 1rem; color: var(--ink-2); font-size: 0.9375rem; line-height: 1.55; }
      button { font: inherit; font-size: 0.9375rem; font-weight: 600; min-height: 44px; padding: 0 1.25rem; border: 0; border-radius: 0.6rem;
        background: var(--accent); color: #fff; cursor: pointer; }
      button:focus-visible { outline: 2px solid var(--accent); outline-offset: 2px; }
    </style>
  </head>
  <body>
    <main>
      <svg class="logo" viewBox="0 0 32 32" aria-hidden="true"><rect width="32" height="32" rx="8" fill="${ACCENT}"/>${GLYPH}</svg>${block("en", en)}${block("ar", ar)}
    </main>
  </body>
</html>
`;
}

async function main() {
  await mkdir(path.join(root, "public/icons"), { recursive: true });
  await png(roundedSvg, 192, "public/icons/icon-192.png");
  await png(roundedSvg, 512, "public/icons/icon-512.png");
  await png(fullBleedSvg, 512, "public/icons/icon-maskable-512.png", { opaque: true });
  await png(fullBleedSvg, 180, "src/app/apple-icon.png", { opaque: true });
  await writeFile(path.join(root, "public/offline.html"), offlineHtml());
  console.log("wrote public/offline.html");
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
